    private void formComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_formComponentShown

        DefaultTableModel model = (DefaultTableModel) tableCategory.getModel();
        Connection con = null;
        PreparedStatement pst = null;
        ResultSet rs = null;

        try {
            con = ConnetionProvider.getInstance().getConnection();
            String sql = "SELECT * FROM category";
            pst = con.prepareStatement(sql);
            rs = pst.executeQuery();

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("CategoryID"),
                    rs.getString("CategoryName"),});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        } finally {

            try {
                if (rs != null) {
                    rs.close();
                }
                if (pst != null) {
                    pst.close();
                }
                if (con != null) {
                    con.close();
                }
            } catch (Exception ex) {
                ex.printStackTrace();
            }
        }

        btnUpdate.setEnabled(false);

    }//GEN-LAST:event_formComponentShown

    private void tableCategoryMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableCategoryMouseClicked
        int index = tableCategory.getSelectedRow();
        TableModel model = tableCategory.getModel();

        String id = model.getValueAt(index, 0).toString();
        CategoryPk = Integer.parseInt(id);

        String CategoryName = model.getValueAt(index, 1).toString();
        txtName.setText(CategoryName);

        btnSave.setEnabled(false);
        btnUpdate.setEnabled(true);
    }//GEN-LAST:event_tableCategoryMouseClicked

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        String CategoryName = txtName.getText();

        if (validateFields()) {
            JOptionPane.showMessageDialog(null, "All fields are required");
        } else {
            Connection con = null;
            PreparedStatement ps = null;
            try {
                con = ConnetionProvider.getInstance().getConnection();
                ps = con.prepareStatement("UPDATE category SET CategoryName=? WHERE CategoryID=?");
                ps.setString(1, CategoryName);
                ps.setInt(2, CategoryPk);

                ps.executeUpdate();
                JOptionPane.showMessageDialog(null, "Category Updated Successfully");

                setVisible(false);
                new ManageCategory().setVisible(true);

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            } finally {
                try {
                    if (ps != null) {
                        ps.close();
                    }
                    if (con != null) {
                        con.close();
                    }
                } catch (Exception ex) {
                    ex.printStackTrace();
                }
            }
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

