    private void loadUserReport() {
        try {
            Connection con = ConnetionProvider.getInstance().getConnection();
            PreparedStatement pst = con.prepareStatement("SELECT UserID, UserName, UserRole, Email, Password, MobileNumber, Status, Address FROM user");
            ResultSet rs = pst.executeQuery();

            JTable reportTable = new JTable();

            Vector<String> headers = new Vector();

            headers.add("User ID");
            headers.add("User Name");
            headers.add("User Role");
            headers.add("Email");
            headers.add("Password");
            headers.add("MobileNumber");
            headers.add("Status");
            headers.add("Address");
            Vector<Vector> tableRows = new Vector();

            // Add rows to the table
            while (rs.next()) {
                Vector<String> row = new Vector();
                row.add(rs.getString("UserID"));
                row.add(rs.getString("UserName"));
                row.add(rs.getString("UserRole"));
                row.add(rs.getString("Email"));
                row.add(rs.getString("Password"));
                row.add(rs.getString("MobileNumber"));
                row.add(rs.getString("Status"));
                row.add(rs.getString("Address"));
                tableRows.add(row);
            }
            DefaultTableModel dtm = new DefaultTableModel(tableRows, headers);
            reportTable.setModel(dtm);
            rs.close();
            pst.close();
            con.close();
            
            InputStream filePath = getClass().getClassLoader().getResourceAsStream("JIAT/Report/userReport.jasper");
            if (filePath == null) {
                JOptionPane.showMessageDialog(null, "User report template not found.", "Report Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            HashMap<String,Object> parameters = new HashMap();
            JRTableModelDataSource jRTableModelDataSource = new JRTableModelDataSource(dtm);
            JasperPrint jasperPrint = JasperFillManager.fillReport(filePath, parameters, jRTableModelDataSource);

            // Auto-save the report to a writable folder (avoids the viewer's C:\ save error)
            InventoryUtils.ensureBillDirectory();
            String outPath = InventoryUtils.getReportDir()
                    + "UserReport_" + new SimpleDateFormat("yyyyMMdd_HHmmss").format(new Date()) + ".pdf";
            JasperExportManager.exportReportToPdfFile(jasperPrint, outPath);

            JasperViewer.viewReport(jasperPrint, false);
            JOptionPane.showMessageDialog(null, "Report saved to:\n" + outPath);
        } catch (SQLException | JRException e) {
            JOptionPane.showMessageDialog(null, "Error generating user report: " + e.getMessage());
            e.printStackTrace();
        }

    }
