    private void tableOrdersMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableOrdersMouseClicked

        int index = tableOrders.getSelectedRow();
        if (index >= 0) {
            TableModel model = tableOrders.getModel();
            String orderId = model.getValueAt(index, 0).toString(); // e.g., "1", "15", etc.

            // Pass raw orderId (no prefix)
            PdfOpener.openPdfByOrderId(orderId);
        }


    }//GEN-LAST:event_tableOrdersMouseClicked


    private void tableCustomerMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableCustomerMouseClicked

        int index = tableCustomer.getSelectedRow();
        TableModel model = tableCustomer.getModel();

        String OrderID = model.getValueAt(index, 0).toString();

        DefaultTableModel orderModel = (DefaultTableModel) tableOrders.getModel();
        orderModel.setRowCount(0);

        Connection con = null;
        PreparedStatement pst = null;
        ResultSet rs = null;

        try {
            con = ConnetionProvider.getInstance().getConnection();
            String sql = "SELECT * FROM orderdetails WHERE CustomerID = ?";
            pst = con.prepareStatement(sql);
            pst.setString(1, OrderID);
            rs = pst.executeQuery();

            while (rs.next()) {
                orderModel.addRow(new Object[]{
                    rs.getString("OrderID"),
                    rs.getString("OrderDate"),
                    rs.getString("TatalPaid"),});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }//GEN-LAST:event_tableCustomerMouseClicked

    private void formComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_formComponentShown
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel) tableCustomer.getModel();
        Connection con = null;
        PreparedStatement pst = null;
        ResultSet rs = null;

        try {
            con = ConnetionProvider.getInstance().getConnection();
            String sql = "SELECT * FROM customer";
            pst = con.prepareStatement(sql);
            rs = pst.executeQuery();

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("CustomerID"),
                    rs.getString("CustomerName"),
                    rs.getString("MobileNumber"),
                    rs.getString("Email"),});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        } finally {
            try {
                if (rs != null) {
                    rs.close();
                }
                if (pst != null) {
                    pst.close();
                }
                if (con != null) {
                    con.close();
                }
            } catch (Exception ex) {
                ex.printStackTrace();
            }
        }


    }//GEN-LAST:event_formComponentShown

