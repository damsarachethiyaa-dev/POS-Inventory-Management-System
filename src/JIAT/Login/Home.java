    public void load() {

        userCount = 0;
        productCount = 0;
        oderCount = 0;

        Connection con = null;
        PreparedStatement pst = null;
        ResultSet rs = null;

        try {
            con = ConnetionProvider.getInstance().getConnection();
            String sql = "SELECT * FROM product ";
            pst = con.prepareStatement(sql);
            rs = pst.executeQuery();

            while (rs.next()) {
                productCount++;
            }
            jLabePCount.setText(String.valueOf(productCount));

            con = ConnetionProvider.getInstance().getConnection();
            String sql1 = "SELECT * FROM customer";
            pst = con.prepareStatement(sql1);
            rs = pst.executeQuery();

            while (rs.next()) {
                userCount++;
            }
            jLabelUCount.setText(String.valueOf(userCount));

            con = ConnetionProvider.getInstance().getConnection();
            String sql2 = "SELECT * FROM orderdetails";
            pst = con.prepareStatement(sql2);
            rs = pst.executeQuery();
            while (rs.next()) {
                oderCount++;
            }
            jLabeloCunt.setText(String.valueOf(oderCount));

        } catch (Exception e) {
            e.printStackTrace();
            Logs.logger.log(Level.WARNING, "Card Loading Erro", e);
        }
    }

