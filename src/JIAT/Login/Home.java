    public void loadProducttable() {
        Connection con = null;
        PreparedStatement pst = null;
        ResultSet rs = null;

        try {
            con = ConnetionProvider.getInstance().getConnection();
            String sql = "SELECT * FROM product INNER JOIN category ON product.CategoryFK = category.CategoryID WHERE `Quantity` < '50'";
            pst = con.prepareStatement(sql);
            rs = pst.executeQuery();

            DefaultTableModel dtm = (DefaultTableModel) tableDashboard.getModel();
            dtm.setRowCount(0);
            while (rs.next()) {
                Vector<String> row = new Vector();
                String ProductId = rs.getString("ProductId");
                String ProductName = rs.getString("ProductName");
                String Quantity = rs.getString("Quantity");
                String Price = rs.getString("Price");
                String Description = rs.getString("Description");
                String CategoryName = rs.getString("CategoryName");

                row.add(ProductId);
                row.add(ProductName);
                row.add(Quantity);
                row.add(Price);
                row.add(Description);
                row.add(CategoryName);
                dtm.addRow(row);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

