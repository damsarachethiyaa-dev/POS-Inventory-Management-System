    private void button1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_button1ActionPerformed
        String noOfUnite = txtOrderQuantity.getText();

        if (!noOfUnite.equals("")) {
            String ProductName = txtProductName.getText();
            String ProductDescription = txtProductDescription.getText();
            String ProductPrice = txtProductPrice.getText();

            int quantityOrdered = Integer.parseInt(noOfUnite);
            int unitPrice = Integer.parseInt(ProductPrice);
            int totalPrice = quantityOrdered * unitPrice;

            int checkStock = 0;
            int checkProductAlreadyExistInCart = 0;

            Connection con = null;
            PreparedStatement ps = null;
            ResultSet rs = null;

            try {
                con = ConnetionProvider.getInstance().getConnection();
                ps = con.prepareStatement("SELECT * FROM product WHERE ProductID = ?");
                ps.setInt(1, productPk);
                rs = ps.executeQuery();

                if (rs.next()) {
                    int availableQty = rs.getInt("Quantity");
                    if (availableQty >= quantityOrdered) {
                        checkStock = 1;
                    } else {
                        JOptionPane.showMessageDialog(null, "Product is out of stock. Only " + availableQty + " left.");
                    }
                }

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            } finally {
                try {
                    if (rs != null) {
                        rs.close();
                    }
                    if (ps != null) {
                        ps.close();
                    }
                    if (con != null) {
                        con.close();
                    }
                } catch (Exception ex) {
                    ex.printStackTrace();
                }
            }

            if (checkStock == 1) {
                DefaultTableModel model = (DefaultTableModel) tableCart.getModel();

                // Check if product already in cart
                for (int i = 0; i < tableCart.getRowCount(); i++) {
                    if (Integer.parseInt(model.getValueAt(i, 0).toString()) == productPk) {
                        checkProductAlreadyExistInCart = 1;
                        JOptionPane.showMessageDialog(null, "Product already exists in the cart");
                        break;
                    }
                }

                // If not, add to cart
                if (checkProductAlreadyExistInCart == 0) {
                    model.addRow(new Object[]{
                        productPk, ProductName, noOfUnite, ProductPrice, ProductDescription, totalPrice
                    });

                    finalTptalPrice = finalTptalPrice + totalPrice;
                    lblFinalTotal.setText(String.valueOf(finalTptalPrice));
                    JOptionPane.showMessageDialog(null, "Added successfully");
                }
            }
            clearProductFileds();
        } else {
            JOptionPane.showMessageDialog(null, "Product quantity and details are required.");
        }


    }//GEN-LAST:event_button1ActionPerformed

