    private void formComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_formComponentShown

// Disable text fields
        txtCustomerName.setEditable(false);
        txtCustomerMobileNumber.setEditable(false);
        txtCustomerEmail.setEditable(false);
        txtProductName.setEditable(false);
        txtProductPrice.setEditable(false);
        txtProductDescription.setEditable(false);

// Get table models
        DefaultTableModel model = (DefaultTableModel) tableCustomer.getModel();
        DefaultTableModel productModel = (DefaultTableModel) tableProduct.getModel();

        Connection con = null;
        PreparedStatement pst = null;
        ResultSet rs = null;

        try {
            con = ConnetionProvider.getInstance().getConnection();

            // Load customers
            String sqlCustomer = "SELECT * FROM customer";
            pst = con.prepareStatement(sqlCustomer);
            rs = pst.executeQuery();

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("CustomerId"),
                    rs.getString("CustomerName"),
                    rs.getString("MobileNumber"),
                    rs.getString("Email")
                });
            }
            rs.close();
            pst.close();

            // Load products with category info
            String sqlProduct = "SELECT * from product inner join category on product.CategoryFK = category.CategoryId";
            pst = con.prepareStatement(sqlProduct);
            rs = pst.executeQuery();

            while (rs.next()) {
                productModel.addRow(new Object[]{
                    rs.getString("ProductId"),
                    rs.getString("ProductName"),
                    rs.getString("Price"),
                    rs.getString("Quantity"),
                    rs.getString("Description"),
                    rs.getString("CategoryID"),
                    rs.getString("CategoryName")
                });
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        } finally {
            try {
                if (rs != null) {
                    rs.close();
                }
                if (pst != null) {
                    pst.close();
                }
                if (con != null) {
                    con.close();
                }
            } catch (Exception ex) {
                ex.printStackTrace();
            }
        }

        //btnUpdate.setEnabled(false);
    }//GEN-LAST:event_formComponentShown

