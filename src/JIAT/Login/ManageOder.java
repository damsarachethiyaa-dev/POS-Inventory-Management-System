    private void btnSaveOrderDetailsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveOrderDetailsActionPerformed
        if (finalTptalPrice == 0 || txtCustomerName.getText().equals("")) {
            JOptionPane.showMessageDialog(null, "Please add products to cart and select a customer.");
            return;
        }

        if (tableCart.getRowCount() == 0) {
            JOptionPane.showMessageDialog(null, "Please add products to cart.");
            return;
        }

        String orderId = getUniqeId("Bill-");
        DefaultTableModel dtm = (DefaultTableModel) tableCart.getModel();
        Connection con = null;

        try {
            con = ConnetionProvider.getInstance().getConnection();

            // Update product quantities
            PreparedStatement pst = con.prepareStatement("UPDATE product SET Quantity = Quantity - ? WHERE ProductID = ?");
            for (int i = 0; i < tableCart.getRowCount(); i++) {
                int quantity = Integer.parseInt(dtm.getValueAt(i, 2).toString());
                int productId = Integer.parseInt(dtm.getValueAt(i, 0).toString());
                pst.setInt(1, quantity);
                pst.setInt(2, productId);
                pst.executeUpdate();
            }
            pst.close();

            // Insert order details
            PreparedStatement ps = con.prepareStatement(
                    "INSERT INTO orderdetails(OrderID, CustomerID, OrderDate, TatalPaid) VALUES (?, ?, ?, ?)");
            String date = new SimpleDateFormat("dd-MM-yyyy").format(Calendar.getInstance().getTime());
            ps.setString(1, orderId);
            ps.setInt(2, customerPk);
            ps.setString(3, date);
            ps.setString(4, String.valueOf(finalTptalPrice));
            ps.executeUpdate();
            ps.close();

            // Generate PDF
            String pdfPath = PdfGenerator.generateBill(orderId, finalTptalPrice, tableCart);

            if (pdfPath != null) {
                PdfOpener.openPdf(pdfPath);
            } else {
                JOptionPane.showMessageDialog(null, "Failed to generate bill PDF.");
            }

            // Move to order management screen
            setVisible(false);
            new ManageOder().setVisible(true);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
            e.printStackTrace();
        } finally {
            try {
                if (con != null) {
                    con.close();
                }
            } catch (Exception ex) {
                ex.printStackTrace();
            }
        }

    }//GEN-LAST:event_btnSaveOrderDetailsActionPerformed

