    private void getALLCategory() {
        Connection con = null;
        PreparedStatement ps = null;
        ResultSet rs = null;
        try {
            con = ConnetionProvider.getInstance().getConnection();
            ps = con.prepareStatement("select * from category");
            rs = ps.executeQuery();

            ComboBoxCategory.removeAllItems();
            while (rs.next()) {
                ComboBoxCategory.addItem(rs.getString("CategoryID") + " - " + rs.getString("CategoryName"));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        } finally {
            try {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
                if (con != null) {
                    con.close();
                }
            } catch (Exception ex) {
                ex.printStackTrace();
            }
        }
    }

    private boolean valideFields(String fromType) {
        if (fromType.equals("edit") && !txtName.getText().equals("") && !txtPrice.getText().equals("") && !txtDescription.getText().equals("")) {
            return false;
        } else if (fromType.equals("new") && !txtName.getText().equals("") && !txtPrice.getText().equals("") && !txtDescription.getText().equals("") && !txtQuantity.getText().equals("")) {
            return false;
        }
        return true;
    }

