    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed

        String Name = txtName.getText();
        String Price = txtPrice.getText();
        String Description = txtDescription.getText();
        String CategoryFK = (String) ComboBoxCategory.getSelectedItem();

        if (valideFields("edit")) {
            JOptionPane.showMessageDialog(null, "All fields are required");
        } else {
            String[] CategoryID = CategoryFK.split("-", 0); // split to get the ID only
            Connection con = null;
            PreparedStatement ps = null;

            try {
                con = ConnetionProvider.getInstance().getConnection();
                ps = con.prepareStatement("UPDATE product SET ProductName=?, Price=?, Description=?, CategoryFK=? WHERE ProductID=?");
                ps.setString(1, Name);
                ps.setString(2, Price);
                ps.setString(3, Description);
                ps.setInt(4, Integer.parseInt(CategoryID[0].trim()));
                ps.setInt(5, productPk);

                ps.executeUpdate();
                JOptionPane.showMessageDialog(null, "Product Updated Successfully");

                setVisible(false);
                new ManageProduct().setVisible(true);
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            } finally {
                try {
                    if (ps != null) {
                        ps.close();
                    }
                    if (con != null) {
                        con.close();
                    }
                } catch (Exception ex) {
                    ex.printStackTrace();
                }
            }
        }

    }//GEN-LAST:event_btnUpdateActionPerformed

