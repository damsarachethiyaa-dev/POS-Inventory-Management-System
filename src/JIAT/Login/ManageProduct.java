    private void formComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_formComponentShown

        getALLCategory();
        DefaultTableModel model = (DefaultTableModel) tableProduct.getModel();
        Connection con = null;
        PreparedStatement pst = null;
        ResultSet rs = null;

        try {
            con = ConnetionProvider.getInstance().getConnection();
            String sql = "SELECT * FROM product INNER JOIN category ON product.CategoryFK = category.CategoryID";
            pst = con.prepareStatement(sql);
            rs = pst.executeQuery();

            model.setRowCount(0);

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("ProductId"),
                    rs.getString("ProductName"),
                    rs.getString("Quantity"),
                    rs.getString("Price"),
                    rs.getString("Description"),
                    rs.getString("CategoryFK"),
                    rs.getString("CategoryName")
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        } finally {
            try {
                if (rs != null) {
                    rs.close();
                }
                if (pst != null) {
                    pst.close();
                }
                if (con != null) {
                    con.close();
                }
            } catch (Exception ex) {
                ex.printStackTrace();
            }
        }

        btnUpdate.setEnabled(false);

    }//GEN-LAST:event_formComponentShown

    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

        String Name = txtName.getText();
        String Quantity = txtQuantity.getText();
        String Price = txtPrice.getText();
        String Description = txtDescription.getText();
        String CategoryFK = (String) ComboBoxCategory.getSelectedItem();

        if (valideFields("new")) {
            JOptionPane.showMessageDialog(null, "All fields are required");
        } else {
            String[] CategoryID = CategoryFK.split("-", 0); // get only ID part
            Connection con = null;
            PreparedStatement ps = null;

            try {
                con = ConnetionProvider.getInstance().getConnection();
                ps = con.prepareStatement("INSERT INTO product (ProductName, Quantity, Price, Description, CategoryFK) VALUES (?, ?, ?, ?, ?)");
                ps.setString(1, Name);
                ps.setString(2, Quantity);
                ps.setString(3, Price);
                ps.setString(4, Description);
                ps.setInt(5, Integer.parseInt(CategoryID[0].trim()));

                ps.executeUpdate();
                JOptionPane.showMessageDialog(null, "Product Added Successfully");

                setVisible(false);
                new ManageProduct().setVisible(true);
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            } finally {
                try {
                    if (ps != null) {
                        ps.close();
                    }
                    if (con != null) {
                        con.close();
                    }
                } catch (Exception ex) {
                    ex.printStackTrace();
                }
            }
        }


    }//GEN-LAST:event_btnSaveActionPerformed

